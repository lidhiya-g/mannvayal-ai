// Helper functions for easy querying
export function getAllStates(): StateOrUTInfo[] {
  return ALL_INDIAN_STATES_AND_UTS;
}

export function getStateByName(name: string): StateOrUTInfo | undefined {
  const norm = name.trim().toLowerCase();
  return ALL_INDIAN_STATES_AND_UTS.find((s) => s.name.toLowerCase() === norm);
}

export function getStateById(id: string): StateOrUTInfo | undefined {
  return ALL_INDIAN_STATES_AND_UTS.find((s) => s.id === id);
}

export function getDistrictsByState(stateName: string): DistrictInfo[] {
  const state = getStateByName(stateName);
  return state ? state.districts : [];
}

export function getDistrictByName(districtName: string): DistrictInfo | undefined {
  const norm = districtName.trim().toLowerCase();
  for (const s of ALL_INDIAN_STATES_AND_UTS) {
    const match = s.districts.find((d) => d.name.toLowerCase() === norm);
    if (match) return match;
  }
  return undefined;
}

export function searchLocations(query: string): {
  type: "STATE" | "DISTRICT" | "SUBDISTRICT";
  state: string;
  district?: string;
  subdistrict?: string;
  label: string;
  details: string;
}[] {
  if (!query || query.trim().length === 0) return [];
  const q = query.trim().toLowerCase();
  const results: any[] = [];

  for (const s of ALL_INDIAN_STATES_AND_UTS) {
    if (s.name.toLowerCase().includes(q)) {
      results.push({
        type: "STATE",
        state: s.name,
        label: `${s.name} (${s.type === "UNION_TERRITORY" ? "UT" : "State"})`,
        details: `${s.zone} India • ${s.agroClimaticZone}`,
      });
    }

    for (const d of s.districts) {
      if (d.name.toLowerCase().includes(q)) {
        results.push({
          type: "DISTRICT",
          state: s.name,
          district: d.name,
          label: `${d.name}, ${s.name}`,
          details: `Rainfall: ~${d.typicalAnnualRainfallMm}mm/yr • Crops: ${d.majorCrops.slice(0, 3).join(", ")}`,
        });
      }

      for (const sub of d.subdistricts) {
        if (sub.toLowerCase().includes(q)) {
          results.push({
            type: "SUBDISTRICT",
            state: s.name,
            district: d.name,
            subdistrict: sub,
            label: `${sub} (Tehsil/Block), ${d.name}, ${s.name}`,
            details: `District: ${d.name} • ${d.primaryAgroContext}`,
          });
        }
      }
    }
  }

  return results.slice(0, 15);
}
